/**
 * Puts the voiced story episodes in the app. For every script in content/stories/ whose
 * voice takes are cached (scripts/story-voice.ts), writes:
 *  - public/stories/<slug>/timing.json: when each spoken piece starts, so the player's
 *    words follow the narration (worked out from the cached takes, which is exactly how
 *    story.mp3 was assembled);
 *  - lib/stories/chapters/<slug>.json: the episode as a SleepChapter (kind "story"), one
 *    "verse" per piece, each section's painting from content/stories/paintings.ts;
 *  - lib/stories/chapters/index.ts: STORY_CHAPTERS in shelf order, and their lengths.
 *
 *   npx tsx scripts/story-build.ts
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { STORY_ART } from "../content/stories/paintings";
import { STORY_SERIES } from "../lib/sleep/books";
import type { SleepChapter, SleepTiming } from "../lib/sleep/types";
import { LEAD_SECONDS, parseStory, PCM_RATE } from "../lib/stories/script";

const OUT = join("lib", "stories", "chapters");
mkdirSync(OUT, { recursive: true });

/** The painting for a section: a reused one, a painted new one, or the fallback until it is painted. */
function imageFor(slug: string, entry: string): string {
  const art = STORY_ART[slug];
  if (!entry.startsWith("new:")) {
    if (!existsSync(join("public", entry))) throw new Error(`${slug}: no painting at ${entry}`);
    return entry;
  }
  const path = `/images/story/${slug}/${entry.slice(4)}.jpg`;
  if (existsSync(join("public", path))) return path;
  unpainted.add(path);
  return art.fallback;
}
const unpainted = new Set<string>();

const built: { chapter: SleepChapter; seconds: number; seriesSlug: string }[] = [];
for (const series of STORY_SERIES) {
  const dir = join("content", "stories", series.slug);
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".md"))) {
    const slug = basename(file, ".md");
    const { meta, pieces } = parseStory(readFileSync(join(dir, file), "utf8"));
    const takes = join("voice-transcripts", "stories", slug);
    const takePath = (i: number) => join(takes, `${String(i).padStart(3, "0")}.pcm`);
    if (!pieces.every((_, i) => existsSync(takePath(i)))) {
      console.log(`  ${slug}: not voiced yet, skipped`);
      continue;
    }
    const art = STORY_ART[slug];
    if (!art) throw new Error(`${slug}: no entry in content/stories/paintings.ts`);
    const sectionTitles = [...new Set(pieces.map((p) => p.section))];
    if (art.sections.length !== sectionTitles.length)
      throw new Error(`${slug}: ${sectionTitles.length} sections but ${art.sections.length} paintings listed`);

    // The same sum story-voice.ts used to assemble story.mp3: lead, then each take and its pause.
    const starts: Record<string, number> = {};
    let at = LEAD_SECONDS;
    pieces.forEach((p, i) => {
      starts[String(i + 1)] = Math.round(at * 100) / 100;
      at += statSync(takePath(i)).size / 2 / PCM_RATE + p.pauseAfter;
    });
    const timing: SleepTiming = { duration: Math.round(at * 100) / 100, verses: starts };
    writeFileSync(join("public", "stories", slug, "timing.json"), JSON.stringify(timing) + "\n");

    const chapter: SleepChapter = {
      slug: `story-${slug}`,
      kind: "story",
      book: series.name,
      chapter: Number(meta.episode),
      title: meta.title,
      translation: "Berean Standard Bible",
      audioSrc: `/stories/${slug}/story.mp3`,
      timingSrc: `/stories/${slug}/timing.json`,
      verses: pieces.map((p, i) => ({
        n: i + 1,
        text: p.text.replace(/\n\n/g, " "),
        ...(i === 0 || pieces[i - 1].section !== p.section ? { heading: p.section } : {}),
        image: imageFor(slug, art.sections[sectionTitles.indexOf(p.section)]),
      })),
    };
    writeFileSync(join(OUT, `${slug}.json`), JSON.stringify(chapter, null, 2) + "\n");
    built.push({ chapter, seconds: Math.round(timing.duration), seriesSlug: series.slug });
  }
}

// Shelf order: series as on the shelf, episodes by number.
built.sort((a, b) =>
  a.seriesSlug === b.seriesSlug
    ? a.chapter.chapter - b.chapter.chapter
    : STORY_SERIES.findIndex((s) => s.slug === a.seriesSlug) - STORY_SERIES.findIndex((s) => s.slug === b.seriesSlug),
);
const id = (slug: string) => `st_${slug.replace(/^story-/, "").replace(/-/g, "_")}`;
const lines = [
  "// Generated by scripts/story-build.ts. Do not edit by hand.",
  'import type { SleepChapter } from "../../sleep/types";',
  ...built.map((b) => `import ${id(b.chapter.slug)} from "./${b.chapter.slug.replace(/^story-/, "")}.json";`),
  "",
  "/** The voiced story episodes, in shelf order (series, then episode). */",
  "export const STORY_CHAPTERS: SleepChapter[] = [",
  ...built.map((b) => `  ${id(b.chapter.slug)} as SleepChapter,`),
  "];",
  "",
  "/** Length of each episode in seconds. */",
  "export const STORY_SECONDS: Record<string, number> = {",
  ...built.map((b) => `  "${b.chapter.slug}": ${b.seconds},`),
  "};",
  "",
];
writeFileSync(join(OUT, "index.ts"), lines.join("\n"));
console.log(`${built.length} episodes built${unpainted.size ? `; ${unpainted.size} new paintings still to paint (scripts/story-paint.ts), fallbacks shown until then` : ""}`);
